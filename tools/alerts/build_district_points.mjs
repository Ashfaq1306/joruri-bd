// Builds packages/core/lib/src/geo/bd_district_points.dart: for each of the 64
// districts, a centre point and up to 12 points spread over the district,
// taken from the coordinates of DGHS-registered hospitals and health
// complexes (one in almost every upazila). Used to decide which districts
// a warning's area (a polygon from BMD) or an earthquake reaches.
// Run from the repo root: node tools/alerts/build_district_points.mjs
import fs from 'node:fs';

const hospitals = JSON.parse(fs.readFileSync('apps/mobile/assets/seed/hospitals.json', 'utf8')).hospitals;
const src = fs.readFileSync('packages/core/lib/src/geo/bd_locations.dart', 'utf8');
const districts = [...src.matchAll(/BdDistrict\('([a-z-]+)', '([a-z]+)'/g)].map((m) => m[1]);
if (districts.length !== 64) throw new Error(`expected 64 districts, got ${districts.length}`);

const km = (a, b) => {
  const r = Math.PI / 180, dLat = (b[0] - a[0]) * r, dLon = (b[1] - a[1]) * r;
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(a[0] * r) * Math.cos(b[0] * r) * Math.sin(dLon / 2) ** 2;
  return 12742 * Math.asin(Math.sqrt(h));
};
const median = (xs) => { const s = [...xs].sort((a, b) => a - b); return s[Math.floor(s.length / 2)]; };
// Bangladesh bounding box: anything outside is a typing error in the source.
const inBd = ([lat, lon]) => lat > 20.5 && lat < 26.7 && lon > 88 && lon < 92.7;

const out = [];
for (const id of districts) {
  let pts = hospitals.filter((h) => h.districtId === id && typeof h.lat === 'number' && typeof h.lng === 'number')
    .map((h) => [h.lat, h.lng]).filter(inBd);
  if (pts.length < 3) throw new Error(`too few points for ${id}`);
  const centre = [median(pts.map((p) => p[0])), median(pts.map((p) => p[1]))];
  pts = pts.filter((p) => km(p, centre) < 75); // drop points typed into the wrong district
  const c = [median(pts.map((p) => p[0])), median(pts.map((p) => p[1]))];
  // Farthest-point sampling: up to 12 points that cover the district.
  const chosen = [];
  while (chosen.length < 12 && pts.length) {
    let best = null, bestD = -1;
    for (const p of pts) {
      const d = Math.min(km(p, c), ...chosen.map((q) => km(p, q)));
      if (d > bestD) { bestD = d; best = p; }
    }
    if (bestD < 4) break;
    chosen.push(best);
  }
  const r2 = (x) => Math.round(x * 100) / 100;
  out.push({ id, centre: c.map(r2), points: chosen.map((p) => p.map(r2)) });
}

const lines = out.map((d) => `    '${d.id}': BdDistrictArea(${d.centre[0]}, ${d.centre[1]}, [${d.points.map((p) => `${p[0]}, ${p[1]}`).join(', ')}]),`);
fs.writeFileSync('packages/core/lib/src/geo/bd_district_points.dart', `// GENERATED by tools/alerts/build_district_points.mjs from the coordinates of
// DGHS-registered hospitals. Do not edit by hand.

/// A district's centre and points spread over it (lat, lon pairs, flat).
class BdDistrictArea {
  const BdDistrictArea(this.lat, this.lon, this.flatPoints);
  final double lat;
  final double lon;
  final List<double> flatPoints;

  /// The centre first, then the spread points.
  Iterable<(double, double)> get points sync* {
    yield (lat, lon);
    for (var i = 0; i + 1 < flatPoints.length; i += 2) {
      yield (flatPoints[i], flatPoints[i + 1]);
    }
  }
}

const bdDistrictAreas = <String, BdDistrictArea>{
${lines.join('\n')}
};
`);
for (const id of ['dhaka', 'coxs-bazar', 'sylhet', 'rangpur', 'khulna', 'bhola', 'bandarban']) {
  const d = out.find((x) => x.id === id); console.log(id, d.centre, d.points.length);
}
