// Builds apps/mobile/assets/seed/medicines.json from the DGDA price download.
// In: medicines_list.json, prices.jsonl   Out: medicines.json (+ medicines_report.txt)
// Leaves out veterinary products (DAR class 077) and raw materials.
import fs from 'node:fs';
const DOWNLOADED_ON = process.env.DOWNLOADED_ON || new Date().toISOString().slice(0, 10);
const OUT = '../../apps/mobile/assets/seed/medicines.json';
const list = JSON.parse(fs.readFileSync('medicines_list.json', 'utf8'));
const prices = new Map();
for (const l of fs.readFileSync('prices.jsonl', 'utf8').split('\n')) if (l) { const p = JSON.parse(l); prices.set(p.href, p); }

const NOT_FOR_PEOPLE = /^(raw materials|kg|liter|bolus|pour on.*|water soluble powder)$/i;
const clean = (s) => String(s || '').replace(/\s+/g, ' ').trim();
const companies = [], companyIdx = new Map();
const rows = []; let vet = 0, raw = 0, noPrice = 0, notFetched = 0;
const seen = new Set();
for (const m of list) {
  if (/-077$/.test(m.dar) || /\bvet\b/i.test(m.brand)) { vet++; continue; }
  if (NOT_FOR_PEOPLE.test(clean(m.form))) { raw++; continue; }
  const p = prices.get(m.href);
  if (!p) notFetched++;
  // generic and strength: the price page splits them; the list has "Generic 500 mg"
  const generic = clean(p?.generic) || clean(m.genericStrength);
  let strength = clean(p?.strength);
  if (!strength && generic !== clean(m.genericStrength)) strength = clean(m.genericStrength.slice(generic.length));
  const packs = [];
  for (const k of p?.packs || []) {
    const v = parseFloat(String(k.unitPrice).replace(/,/g, ''));
    if (Number.isFinite(v) && v > 0) packs.push([clean(k.pack), Math.round(v * 100) / 100]);
  }
  if (p && !packs.length) noPrice++;
  const company = clean(m.company);
  if (!companyIdx.has(company)) { companyIdx.set(company, companies.length); companies.push(company); }
  const key = [m.brand, generic, strength, m.form, company].join('|').toLowerCase();
  if (seen.has(key) && !packs.length) continue;
  seen.add(key);
  rows.push([clean(m.brand), generic, strength, clean(m.form), companyIdx.get(company), clean(m.dar), packs]);
}
rows.sort((a, b) => a[0].localeCompare(b[0]));
fs.writeFileSync(OUT, JSON.stringify({
  schemaVersion: 1, downloadedOn: DOWNLOADED_ON,
  source: 'DGDA medicine price list, http://180.211.137.202:9310/Allopathic/ (Medicine Information / Medicine Price Detail)',
  format: 'medicines: [brand, generic, strength, form, companyIndex, darNumber, [[pack, unitPriceTaka], ...]]. Generated by tools/dgda-import/build_medicines.mjs; do not edit by hand.',
  companies, medicines: rows }));
const report = `medicines ${rows.length} (with price ${rows.filter((r) => r[6].length).length}); companies ${companies.length}; left out: veterinary ${vet}, raw/bulk ${raw}; price page without price ${noPrice}; not fetched ${notFetched}`;
fs.writeFileSync('medicines_report.txt', report + '\n');
console.log(report);
