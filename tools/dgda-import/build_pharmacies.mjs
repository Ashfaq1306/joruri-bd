// Builds the app's pharmacy files from the DGDA register download.
// In: pharmacies_raw.jsonl   Out: apps/mobile/assets/seed/pharmacies/<districtId>.json + pharmacies_report.txt
import fs from 'node:fs';

const DOWNLOADED_ON = process.env.DOWNLOADED_ON || new Date().toISOString().slice(0, 10);
// Keep shops whose licence is valid or expired less than 5 years ago: the online register
// often lags renewals (most Dhaka city shops show old dates), but a licence that ran out
// long ago usually means the shop closed. The app labels expired licences and lists them last.
const KEEP_FROM = new Date(new Date(DOWNLOADED_ON).getTime() - 5 * 365 * 864e5);
const OUT_DIR = '../../apps/mobile/assets/seed/pharmacies';

const DISTRICT_IDS = 'barguna barishal bhola jhalokati patuakhali pirojpur bandarban brahmanbaria chandpur chattogram cumilla coxs-bazar feni khagrachhari lakshmipur noakhali rangamati dhaka faridpur gazipur gopalganj kishoreganj madaripur manikganj munshiganj narayanganj narsingdi rajbari shariatpur tangail bagerhat chuadanga jashore jhenaidah khulna kushtia magura meherpur narail satkhira jamalpur mymensingh netrokona sherpur bogura chapainawabganj joypurhat naogaon natore pabna rajshahi sirajganj dinajpur gaibandha kurigram lalmonirhat nilphamari panchagarh rangpur thakurgaon habiganj moulvibazar sunamganj sylhet'.split(' ');
const ALIAS = { jhalokathi: 'jhalokati', khagrachari: 'khagrachhari', maulvibazar: 'moulvibazar', netrakona: 'netrokona', 'cox-s-bazar': 'coxs-bazar',
  coxsbazar: 'coxs-bazar', kishoregonj: 'kishoreganj', chittagong: 'chattogram', comilla: 'cumilla', barisal: 'barishal', jessore: 'jashore', bogra: 'bogura',
  'chapai-nawabganj': 'chapainawabganj', 'nawabganj': 'chapainawabganj', laxmipur: 'lakshmipur', jhenaidaha: 'jhenaidah', 'moulvi-bazar': 'moulvibazar' };
function districtId(name) {
  const k = String(name || '').toLowerCase().replace(/'/g, '').replace(/[^a-z]+/g, '-').replace(/^-|-$/g, '');
  const id = ALIAS[k] || k;
  return DISTRICT_IDS.includes(id) ? id : null;
}
function date(s) { const m = /^(\d\d)-(\d\d)-(\d{4})$/.exec(s || ''); if (!m) return null; const d = new Date(`${m[3]}-${m[2]}-${m[1]}T00:00:00Z`); return isNaN(d) || +m[3] < 1970 || +m[3] > 2040 ? null : d; }
// First usable Bangladeshi number: mobile 01[3-9]xxxxxxxx or landline with area code.
function phone(raw) {
  for (const part of String(raw || '').replace(/[০-৯]/g, (c) => '০১২৩৪৫৬৭৮৯'.indexOf(c)).split(/[,;/]|\s{2,}|\bor\b/)) {
    let d = part.replace(/\D/g, '');
    if (d.startsWith('880')) d = d.slice(2);
    if (d.length === 10 && /^1[3-9]/.test(d)) d = '0' + d;
    if (/^(\d)\1+$/.test(d.slice(1)) || /^0+$/.test(d)) continue;
    if (/^01[3-9]\d{8}$/.test(d) && !/^01[3-9](\d)\1{7}$/.test(d)) return d;
    if (/^0[2-9]\d{6,9}$/.test(d) && !d.startsWith('01')) return d;
  }
  return '';
}
const clean = (s) => String(s || '').replace(/\s+/g, ' ').replace(/^[-.,\s]+|[-,\s]+$/g, '').trim();
const title = (s) => (s === s.toUpperCase() && /[A-Z]{4}/.test(s) ? s.toLowerCase().replace(/\b[a-z]/g, (c) => c.toUpperCase()) : s);

const raw = fs.readFileSync('pharmacies_raw.jsonl', 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l)).filter((r) => r && r.dgdaId);
const by = Object.fromEntries(DISTRICT_IDS.map((d) => [d, []]));
const unknownDistrict = {}; let old = 0, noDate = 0, dup = 0, kept = 0, withPhone = 0;
const seen = new Set();
for (const r of raw) {
  const dist = districtId(r.district);
  if (!dist) { unknownDistrict[r.district] = (unknownDistrict[r.district] || 0) + 1; continue; }
  const until = date(r.validUpto);
  if (!until) { noDate++; continue; }
  if (until < KEEP_FROM) { old++; continue; }
  const lic = clean(r.licence).toLowerCase();
  if (lic && seen.has(lic)) { dup++; continue; }
  if (lic) seen.add(lic);
  const name = title(clean(r.name));
  if (!name) continue;
  const p = { id: `dgda-${r.dgdaId}`, name, area: title(clean(r.upazila)), address: title(clean(r.address)) };
  if (p.address === '-' || p.address.toLowerCase() === p.area.toLowerCase()) delete p.address;
  const tel = phone(r.phone); if (tel) { p.phone = tel; withPhone++; }
  p.licence = clean(r.licence);
  p.validUpto = until.toISOString().slice(0, 10);
  by[dist].push(p); kept++;
}
fs.mkdirSync(OUT_DIR, { recursive: true });
const lines = [];
for (const [dist, list] of Object.entries(by)) {
  list.sort((a, b) => a.area.localeCompare(b.area) || a.name.localeCompare(b.name));
  fs.writeFileSync(`${OUT_DIR}/${dist}.json`, JSON.stringify({
    schemaVersion: 1, districtId: dist, downloadedOn: DOWNLOADED_ON,
    source: 'DGDA Allopathic Retail Pharmacy register, https://dgdagov.info/index.php/pharmacies/allopathic-retail-pharmacy',
    note: 'Generated by tools/dgda-import/build_pharmacies.mjs. Do not edit by hand. Pharmacist/proprietor names and NID are not included.',
    pharmacies: list }));
  lines.push(`${dist.padEnd(16)} ${String(list.length).padStart(6)}  phone ${list.filter((p) => p.phone).length}`);
}
const report = [`DGDA register rows ${raw.length}; kept ${kept} (with phone ${withPhone}); licence ended before ${KEEP_FROM.toISOString().slice(0, 10)}: ${old}; no date ${noDate}; duplicate licence ${dup}`,
  `unknown district: ${JSON.stringify(unknownDistrict)}`, ...lines].join('\n');
fs.writeFileSync('pharmacies_report.txt', report + '\n');
console.log(report);
